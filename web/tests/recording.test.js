// Every fixture is generated by the shared physical World, with actual sensor acquisitions.
function fixture({
  scene = DEFAULT_SCENE,
  vehicles = [{ id: "alpha" }],
  setup = {},
} = {}) {
  const initialWorld = validateWorldConfig({
    scene,
    wind: { speed: 0, direction: 0 },
    vehicles: vehicles.map((v, index) => {
      const config = validateConfig({ seed: 100 + index, ...v.config });
      const home = v.home ?? [index * 20, 0];
      return {
        id: v.id,
        name: v.name ?? v.id,
        config,
        spawn: {
          north: home[0],
          east: home[1],
          altitude: config.startOnGround ? 0 : 2,
          heading: 0,
          ...v.spawn,
        },
        home,
        scenario: v.scenario ?? "hover",
        setup: {
          mode: "attitude",
          mission: [],
          gimbal: DEFAULT_GIMBAL_SETTINGS,
          training: "free",
          ...setup,
          ...v.setup,
          sensors: validateSensorConfig({
            ...sensorConfig,
            ...setup.sensors,
            ...v.setup?.sensors,
          }),
        },
      };
    }),
  });
  const world = createWorld(initialWorld);
  const record = {
    format: "flight-lab",
    version: RECORDING_VERSION,
    modelVersion: MODEL_VERSION,
    createdAt: "2026-11-05T00:00:00.000Z",
    dt: 0.005,
    world: clone(initialWorld),
    runtime: {
      speed: 1,
      wallSeconds: 0.05,
      p95LateMs: 0,
      lateTicks: 0,
      skippedWallSeconds: 0,
      renderEnabled: true,
    },
    events: [],
    samples: [],
    sensorFrames: [],
    termination: null,
  };
  function capture() {
    const snapshot = world.snapshot();
    const index =
      record.samples.at(-1)?.tick === snapshot.tick
        ? record.samples.length - 1
        : record.samples.length;
    record.samples[index] = compactWorldSnapshot(snapshot);
    record.sensorFrames[index] = worldSensorFrame(snapshot);
    return snapshot;
  }
  function command(
    type,
    value,
    vehicleId = initialWorld.vehicles[0].id,
    fault,
  ) {
    const { tick, time } = world.snapshot();
    const global = ["scene", "wind", "render"].includes(type);
    if (type === "scene") world.setScene(value);
    else if (type === "wind") world.setWind(value);
    else if (type !== "render") world.command(vehicleId, type === "operatorGimbal" ? "gimbal" : type, value, fault);
    record.events.push({
      tick,
      time,
      type,
      ...(!global ? { vehicleId } : {}),
      ...(value === undefined ? {} : { value: clone(value) }),
      ...(fault === undefined ? {} : { fault }),
    });
    return capture();
  }
  function step(count = 10, cadence = count) {
    for (let i = 1; i <= count; i++) {
      world.step();
      if (i % cadence === 0 || world.snapshot().collisions.length) capture();
      if (world.snapshot().collisions.length) break;
    }
    return capture();
  }
  capture();
  return { record, world, capture, command, step };
}
function shortRecord(options) {
  const f = fixture(options);
  f.step();
  return f.record;
}
function roundTrip(record) {
  const clean = validateRecording(record);
  assert.deepEqual(clean.sensorFrames, record.sensorFrames);
  const restored = validateRecording(JSON.parse(recordingToJson(record)));
  // JSON numbers preserve value but do not distinguish signed zero.
  assert.deepEqual(
    JSON.parse(JSON.stringify(restored)),
    JSON.parse(JSON.stringify(clean)),
  );
  return clean;
}

