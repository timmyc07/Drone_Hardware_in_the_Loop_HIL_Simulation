function tutorialRecord() {
  const f = fixture({
    vehicles: [{ id: "alpha", config: { startOnGround: true } }],
    setup: { training: "tutorial" },
  });
  const acted = new Set();
  let current = f.world.snapshot();
  for (let i = 0; i < 20000 && !current.vehicles[0].training.complete; i++) {
    const progress = current.vehicles[0].training;
    assert.equal(progress.reason, "");
    if (!acted.has(progress.passed)) {
      acted.add(progress.passed);
      if (progress.passed === 1) f.command("arm");
      if (progress.passed === 2) f.command("takeoff");
      if ([4, 5].includes(progress.passed)) {
        f.command("mode", "position");
        f.command("position", {
          north: progress.passed === 4 ? 8 : 0,
          east: 0,
          altitude: 2,
          altitudeReference: "datum",
        });
      }
      if (progress.passed === 6) f.command("mode", "land");
    }
    f.world.step();
    current = f.world.snapshot();
    if (current.tick % 10 === 0) f.capture();
  }
  assert.equal(current.vehicles[0].training.complete, true);
  f.capture();
  f.step(10);
  return f.record;
}
